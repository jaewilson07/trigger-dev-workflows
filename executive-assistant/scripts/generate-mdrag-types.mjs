/**
 * Generate `lib/mdrag-schema.ts` from mdrag's OpenAPI schema, PRUNED to just the
 * `/api/v1/primitives/*` router and the component schemas it transitively
 * references. This replaces the hand-mirrored request/response types the
 * `tasks/mdrag-*.ts` wrappers used to carry (a cross-repo copy that silently
 * drifted when mdrag changed a field — see trigger-dev-workflows#9).
 *
 * Source: MDRAG_OPENAPI_URL (default `${MDRAG_URL}/openapi.json`). On bonker,
 * mdrag is published locally, so run:
 *   MDRAG_OPENAPI_URL=http://localhost:8017/openapi.json npm run generate:mdrag-types
 * Behind Cloudflare Access (wiki.datacrew.space) the fetch needs an X-DC-Token;
 * set MDRAG_TOKEN and it is sent automatically.
 *
 * We prune before codegen so the committed artifact stays small (5 paths + ~16
 * schemas) instead of the full ~15k-line mdrag schema.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const MDRAG_URL = (process.env.MDRAG_URL ?? "https://wiki.datacrew.space").replace(/\/+$/, "");
const OPENAPI_URL = process.env.MDRAG_OPENAPI_URL ?? `${MDRAG_URL}/openapi.json`;
const TOKEN = process.env.MDRAG_TOKEN ?? "";
const PATH_PREFIX = "/api/v1/primitives/";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../lib/mdrag-schema.ts");

/** Collect every `#/components/schemas/<Name>` referenced anywhere in `obj`. */
function collectRefs(obj, acc) {
  if (Array.isArray(obj)) {
    for (const x of obj) collectRefs(x, acc);
  } else if (obj && typeof obj === "object") {
    for (const [k, v] of Object.entries(obj)) {
      if (k === "$ref" && typeof v === "string" && v.startsWith("#/components/schemas/")) {
        acc.add(v.slice("#/components/schemas/".length));
      } else {
        collectRefs(v, acc);
      }
    }
  }
}

async function main() {
  const res = await fetch(OPENAPI_URL, {
    headers: TOKEN ? { "X-DC-Token": TOKEN } : {},
  });
  if (!res.ok) {
    throw new Error(`Failed to fetch ${OPENAPI_URL}: HTTP ${res.status}`);
  }
  const doc = await res.json();

  const paths = Object.fromEntries(
    Object.entries(doc.paths ?? {}).filter(([p]) => p.includes(PATH_PREFIX))
  );
  if (Object.keys(paths).length === 0) {
    throw new Error(`No ${PATH_PREFIX}* paths found in the schema at ${OPENAPI_URL}`);
  }

  const allSchemas = doc.components?.schemas ?? {};
  const closure = new Set();
  const seed = new Set();
  collectRefs(paths, seed);
  const frontier = [...seed];
  for (const s of seed) closure.add(s);
  while (frontier.length) {
    const name = frontier.pop();
    const next = new Set();
    collectRefs(allSchemas[name] ?? {}, next);
    for (const m of next) {
      if (!closure.has(m)) {
        closure.add(m);
        frontier.push(m);
      }
    }
  }

  const schemas = Object.fromEntries(
    [...closure].sort().map((n) => [n, allSchemas[n]]).filter(([, v]) => v)
  );

  const pruned = {
    openapi: doc.openapi ?? "3.1.0",
    info: { title: "mdrag primitives (pruned)", version: doc.info?.version ?? "0" },
    paths,
    components: { schemas },
  };

  const ast = await openapiTS(pruned);
  const body = astToString(ast);
  const header =
    "// AUTO-GENERATED by scripts/generate-mdrag-types.mjs — DO NOT EDIT.\n" +
    "// Source: mdrag OpenAPI, pruned to /api/v1/primitives/*. Regenerate with:\n" +
    "//   MDRAG_OPENAPI_URL=http://localhost:8017/openapi.json npm run generate:mdrag-types\n\n";
  await writeFile(OUT, header + body);
  console.log(`Wrote ${OUT} (${Object.keys(paths).length} paths, ${closure.size} schemas)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
